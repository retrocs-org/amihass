"""Generate native two-plane dashboard art and matching PNG previews."""
from pathlib import Path
import struct,zlib,math
ROOT=Path(__file__).resolve().parents[1]
class Canvas:
 def __init__(self):self.p=[[0]*24 for _ in range(24)]
 def dot(self,x,y,v):
  if 0<=x<24 and 0<=y<24:self.p[y][x]=v
 def rect(self,x,y,w,h,v):
  for yy in range(y,y+h):
   for xx in range(x,x+w):self.dot(xx,yy,v)
 def line(self,x,y,xx,yy,v=1):
  steps=max(abs(xx-x),abs(yy-y),1)
  for k in range(steps+1):self.dot(round(x+(xx-x)*k/steps),round(y+(yy-y)*k/steps),v)
 def box(self,x,y,w,h):self.rect(x,y,w,h,1);self.rect(x+1,y+1,w-2,h-2,2);self.line(x+1,y+1,x+w-2,y+1,3)
 def circle(self,x,y,r,v=1):
  for k in range(72):a=k*math.pi/36;self.dot(round(x+r*math.cos(a)),round(y+r*math.sin(a)),v)
